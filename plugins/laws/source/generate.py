#!/usr/bin/env python3
"""Write the laws:code skill and its rung projections from plugins/laws/source/code/.

Run: python3 plugins/laws/source/generate.py          # write the outputs
     python3 plugins/laws/source/generate.py --check  # exit 1 if an output is stale

Outputs, under plugins/laws/:

  skills/code/SKILL.md               every law at the rung profiles/default.toml gives it
  skills/code/references/rung-s.md   every law at S
  skills/code/references/rung-m.md   every law at M
  agents/code.md                     SKILL.md's body under agent.md's frontmatter: the
                                     laws:code agent, whose system prompt is the laws

skeleton.md fixes the order. Each of its `<!-- include: <file> -->` lines is replaced by
that file verbatim; every other skeleton line is copied as is. Inside the included files:

  <!-- rung: S -->         marks the one paragraph that follows it as serving rung S
  <!-- rung: M -->         ... as serving rung M; unmarked text is L
  <!-- law-index -->       the law tokens, derived from the law headings, in document order
  <!-- framing-index -->   the framing tokens, likewise
  <!-- generated-notice --> the line saying this output is generated, and from what; it sits
                           in the frontmatter as a YAML comment, so it costs the model nothing

Every file under laws/ is a law and every file under framings/ a framing: its first line is
`## [LAW:<file stem>] - ...` (or FRAMING), and the skeleton includes each one exactly once.

A law rendered at L is its source verbatim. At S it is its heading and its S-marked
paragraphs; at M, its heading and its S- and M-marked paragraphs; always in source order.
So S is a subset of M and M of L by construction. Rendering removes the rung lines and
nothing else, and the text outside the laws is the same at every rung.

A profile (profiles/<name>.toml) gives a rung to every law.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "code"
PLUGIN_DIR = HERE.parent
DEFAULT_PROFILE = "default"

GENERATED = (
    "Generated by plugins/laws/source/generate.py from plugins/laws/source/code/."
    " Edit the sources and regenerate; never edit this file."
)
NOTICE = f"# {GENERATED}\n"
INDEX_WIDTH = 84

# Every single-line HTML comment in a source is one of these; anything else is a typo
# that would otherwise ship as visible text in the skill.
DIRECTIVE = re.compile(r"^<!-- (include|rung|law-index|framing-index|generated-notice)(?:: (\S+))? -->$")
SINGLE_LINE_COMMENT = re.compile(r"^<!--.*-->$")
KIND_BY_DIR = {"laws": "LAW", "framings": "FRAMING"}
Rung = Literal["S", "M", "L"]
LADDER: tuple[Rung, ...] = ("S", "M", "L")  # each rung shows its own paragraphs and those of every rung before it
RUNGS = LADDER[:-1]  # the rungs a marker can name; unmarked text is the top rung


class SourceError(Exception):
    pass


@dataclass(frozen=True)
class Unit:
    kind: str  # "LAW" or "FRAMING"
    token: str
    marks: dict[str, int]  # rung -> paragraphs marked with it


def directive(line: str, where: str) -> tuple[str, str | None] | None:
    text = line.rstrip("\n")
    m = DIRECTIVE.match(text)
    if m:
        return m.group(1), m.group(2)
    if SINGLE_LINE_COMMENT.match(text.strip()):
        raise SourceError(f"{where}: unknown directive {text!r}")
    return None


def marked_paragraphs(lines: list[str], where: str) -> dict[str, list[str]]:
    """Rung -> first line of each paragraph marked with it."""
    marked: dict[str, list[str]] = {rung: [] for rung in RUNGS}
    for i, line in enumerate(lines):
        d = directive(line, f"{where}:{i + 1}")
        if d is None or d[0] != "rung":
            continue
        rung = d[1]
        if rung not in RUNGS:
            raise SourceError(f"{where}:{i + 1}: rung must be one of {RUNGS}, got {rung!r}")
        if i > 0 and lines[i - 1].strip():
            raise SourceError(f"{where}:{i + 1}: rung marker sits inside a paragraph; it belongs on the blank line before one")
        following = lines[i + 1] if i + 1 < len(lines) else ""
        if not following.strip() or directive(following, f"{where}:{i + 2}"):
            raise SourceError(f"{where}:{i + 1}: rung marker is not followed by a paragraph")
        marked[rung].append(following)
    return marked


def read_unit(path: Path, kind: str, lines: list[str]) -> Unit:
    heading = f"## [{kind}:{path.stem}] - "
    first = lines[0].rstrip("\n") if lines else ""
    if not first.startswith(heading):
        raise SourceError(f"{path}:1: a {kind} file named {path.stem!r} opens with {heading!r}..., not {first!r}")
    marked = marked_paragraphs(lines, str(path))
    unit = Unit(kind=kind, token=path.stem, marks={rung: len(marked[rung]) for rung in RUNGS})
    if kind == "FRAMING":
        if any(marked.values()):
            raise SourceError(f"{path}: rung markers belong to laws; framing {unit.token!r} has some")
        return unit
    body = [line for line in lines[1:] if line.strip()]
    if len(body) < 2 or directive(body[0], str(path)) != ("rung", "S") or not body[1].startswith("**"):
        raise SourceError(f"law {unit.token!r} ({path}): the paragraph under the heading is not an S-marked bold statement")
    if not any(first.startswith("Diagnostic:") for first in marked["S"]):
        raise SourceError(f"law {unit.token!r} ({path}): no S-marked Diagnostic line")
    return unit


def project(lines: list[tuple[str, str]], rung: Rung) -> list[tuple[str, str]]:
    """A law's (line, where) pairs at rung: verbatim at L; below it, the heading and the
    paragraphs marked with a rung the rung shows, each kept with its marker so rendering
    treats them alike."""
    if rung == LADDER[-1]:
        return lines
    shown = LADDER[:LADDER.index(rung) + 1]
    out = [lines[0]]
    i = 1
    while i < len(lines):
        d = directive(*lines[i])
        if d is not None and d[0] == "rung" and d[1] in shown:
            end = i + 1
            while end < len(lines) and lines[end][0].strip():
                end += 1
            out += [("\n", lines[i][1]), *lines[i:end]]
            i = end
        else:
            i += 1
    return out


def load_profile(path: Path) -> dict[str, Rung]:
    """The profile's rung for every law."""
    try:
        data = tomllib.loads(path.read_text())
    except tomllib.TOMLDecodeError as e:
        raise SourceError(f"{path}: {e}") from e
    if set(data) != {"rungs"}:
        raise SourceError(f"{path}: a profile has exactly [rungs]; got {sorted(data)}")
    rungs = data["rungs"]
    if not isinstance(rungs, dict):
        raise SourceError(f"{path}: rungs must be a table of law = rung")
    bad = {law: rung for law, rung in rungs.items() if rung not in LADDER}
    if bad:
        raise SourceError(f"{path}: rungs must be one of {LADDER}; got {bad}")
    return rungs


def uniform(rung: Rung, laws: list[str]) -> dict[str, Rung]:
    return {law: rung for law in laws}


def wrap_index(items: list[str]) -> list[str]:
    rows: list[list[str]] = [[]]
    for item in items:
        if rows[-1] and len(" · ".join(rows[-1] + [item]) + " ·") > INDEX_WIDTH:
            rows.append([])
        rows[-1].append(item)
    return [" · ".join(row) + (" ·" if i < len(rows) - 1 else "") + "\n" for i, row in enumerate(rows)]


@dataclass(frozen=True)
class Piece:
    lines: list[tuple[str, str]]  # (line, where it came from)
    law: str | None  # the law whose file this is, or None for any other text


@dataclass(frozen=True)
class Source:
    """The sources, read and checked once; render() lays them out at any rungs."""

    pieces: list[Piece]
    units: list[Unit]
    expanded: dict[str, list[str]]  # non-rung directive -> the lines it becomes

    @property
    def laws(self) -> list[str]:
        return [u.token for u in self.units if u.kind == "LAW"]

    def report(self) -> str:
        laws = [u for u in self.units if u.kind == "LAW"]
        marks = " ".join(f"{r}={sum(u.marks[r] for u in laws)}" for r in RUNGS)
        return f"{len(laws)} laws, {len(self.units) - len(laws)} framings, marked paragraphs {marks}"

    def render(self, rungs: dict[str, Rung], where: str) -> str:
        if set(rungs) != set(self.laws):
            missing = [law for law in self.laws if law not in rungs]
            unknown = sorted(set(rungs) - set(self.laws))
            raise SourceError(f"{where}: rungs must name every law once; missing {missing}, unknown {unknown}")
        out: list[str] = []
        for piece in self.pieces:
            lines = piece.lines if piece.law is None else project(piece.lines, rungs[piece.law])
            for line, at in lines:
                d = directive(line, at)
                if d is None:
                    out.append(line)
                elif d[0] == "include":
                    raise SourceError(f"{at}: includes do not nest")
                elif d[0] != "rung":
                    out.extend(self.expanded[d[0]])
        return "".join(out)


def read_source(source: Path = SOURCE) -> Source:
    skeleton = (source / "skeleton.md").read_text().splitlines(keepends=True)
    pieces: list[Piece] = []
    units: list[Unit] = []
    included: set[str] = set()  # laws/ and framings/ files, as the skeleton names them
    for n, line in enumerate(skeleton, 1):
        d = directive(line, f"skeleton.md:{n}")
        if d is None:
            pieces.append(Piece(lines=[(line, f"skeleton.md:{n}")], law=None))
            continue
        if d[0] != "include":
            raise SourceError(f"skeleton.md:{n}: only include lines belong in the skeleton")
        if d[1] is None:
            raise SourceError(f"skeleton.md:{n}: include names no file")
        path = source / d[1]
        if not path.is_file():
            raise SourceError(f"skeleton.md:{n}: included file {d[1]!r} does not exist")
        lines = path.read_text().splitlines(keepends=True)
        parts = Path(d[1]).parts
        kind = KIND_BY_DIR.get(parts[0]) if len(parts) > 1 else None
        law = None
        if kind is None:
            marked_paragraphs(lines, d[1])
        elif len(parts) != 2:
            raise SourceError(f"skeleton.md:{n}: {d[1]!r} is nested; {parts[0]}/ files sit directly in it")
        else:
            unit = read_unit(path, kind, lines)
            units.append(unit)
            included.add(d[1])
            law = unit.token if kind == "LAW" else None
        pieces.append(Piece(lines=[(l, f"{d[1]}:{i}") for i, l in enumerate(lines, 1)], law=law))

    tokens = {kind: [u.token for u in units if u.kind == kind] for kind in ("LAW", "FRAMING")}
    for kind, found in tokens.items():
        if len(set(found)) != len(found):
            raise SourceError(f"duplicate {kind} token in skeleton: {found}")
    for directory in KIND_BY_DIR:
        orphans = sorted({p.relative_to(source).as_posix() for p in (source / directory).rglob("*.md")} - included)
        if orphans:
            raise SourceError(f"skeleton.md includes no line for {directory}/ files: {orphans}")
    expanded = {
        "law-index": wrap_index([f"`{t}`" for t in tokens["LAW"]]),
        "framing-index": wrap_index([f"`[FRAMING:{t}]`" for t in tokens["FRAMING"]]),
        "generated-notice": [NOTICE],
    }
    return Source(pieces=pieces, units=units, expanded=expanded)


def body(skill: str) -> str:
    """The rendered skill without its frontmatter."""
    if not skill.startswith("---\n"):
        raise SourceError("the rendered skill does not open with frontmatter")
    return skill[skill.index("\n---\n", 3) + len("\n---\n"):].lstrip("\n")


def as_reference(skill: str, rung: Rung) -> str:
    """A projection read by path is not a skill: its frontmatter goes, a one-line notice
    takes its place."""
    return (
        f"<!-- {GENERATED} A projection of SKILL.md: every law at rung {rung}, its other paragraphs"
        f" left out; the text outside the laws is SKILL.md's. -->\n\n{body(skill)}"
    )


def as_agent(skill: str, head_path: Path) -> str:
    """The agent's own frontmatter over the skill's body. An agent's description says when to
    delegate to it, which is not when to load the skill, so the two never share one."""
    head = []
    for n, line in enumerate(head_path.read_text().splitlines(keepends=True), 1):
        d = directive(line, f"{head_path.name}:{n}")
        if d is not None and d[0] != "generated-notice":
            raise SourceError(f"{head_path.name}:{n}: only the generated-notice directive belongs in the agent's frontmatter")
        head.append(line if d is None else NOTICE)
    return f"{''.join(head)}\n{body(skill)}"


@dataclass(frozen=True)
class Output:
    path: str  # under the plugin directory
    text: str


@dataclass(frozen=True)
class Build:
    source: Source
    outputs: list[Output]


def build(source_dir: Path = SOURCE) -> Build:
    source = read_source(source_dir)
    profile_path = source_dir / "profiles" / f"{DEFAULT_PROFILE}.toml"
    rungs = load_profile(profile_path)
    projection = {rung: source.render(uniform(rung, source.laws), f"all-{rung}") for rung in ("S", "M")}
    skill = source.render(rungs, str(profile_path))
    return Build(source=source, outputs=[
        Output("skills/code/SKILL.md", skill),
        Output("skills/code/references/rung-s.md", as_reference(projection["S"], "S")),
        Output("skills/code/references/rung-m.md", as_reference(projection["M"], "M")),
        Output("agents/code.md", as_agent(skill, source_dir / "agent.md")),
    ])


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if an output is stale")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--plugin-dir", type=Path, default=PLUGIN_DIR)
    args = parser.parse_args(argv)
    try:
        built = build(args.source)
    except SourceError as e:
        print(f"generate: {e}", file=sys.stderr)
        return 2
    stale = [o for o in built.outputs if not ((args.plugin_dir / o.path).is_file() and (args.plugin_dir / o.path).read_text() == o.text)]
    if args.check:
        for output in stale:
            print(f"generate: {args.plugin_dir / output.path} is stale against {args.source}; run {Path(__file__).name}", file=sys.stderr)
    else:
        for output in stale:
            (args.plugin_dir / output.path).parent.mkdir(parents=True, exist_ok=True)
            (args.plugin_dir / output.path).write_text(output.text)
        written = ", ".join(o.path for o in stale) or "nothing"
        print(f"generate: wrote {written} in {args.plugin_dir}: {built.source.report()}")
    if args.check and stale:
        return 1
    if args.check:
        print(f"generate: {args.plugin_dir} is current: {built.source.report()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
